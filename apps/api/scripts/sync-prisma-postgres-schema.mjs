/**
 * Regenerates `prisma/schema.postgresql.prisma` from `prisma/schema.prisma`
 * (single source of truth for models; only the datasource block differs).
 * Run from apps/api: node scripts/sync-prisma-postgres-schema.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const sqlitePath = path.join(root, "prisma", "schema.prisma");
const outPath = path.join(root, "prisma", "schema.postgresql.prisma");

let raw = fs.readFileSync(sqlitePath, "utf8");
if (!/provider\s*=\s*"sqlite"/.test(raw)) {
  console.error("Expected prisma/schema.prisma to use provider = \"sqlite\".");
  process.exit(1);
}

// Drop leading // comments (sqlite-specific notes) so the generated file is Postgres-accurate.
raw = raw.replace(/^(\s*\/\/[^\n]*\n)+/m, "");

const body = raw.replace(
  /datasource db\s*\{[^}]*\}/s,
  `datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}`
);

const header = `// AUTO-GENERATED by scripts/sync-prisma-postgres-schema.mjs — edit prisma/schema.prisma then re-run: npm run prisma:sync-pg
// Deploy/staging: prisma migrate uses this schema. Local dev: keep using prisma/schema.prisma + SQLite.
`;

fs.writeFileSync(outPath, header + body.trimStart(), "utf8");
console.log("Wrote", path.relative(root, outPath));
